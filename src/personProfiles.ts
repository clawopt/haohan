import type { Entity } from './data'

type Profile = Pick<Entity, 'lifespan' | 'description' | 'milestones' | 'sources' | 'biographyNote'>
const profiles: Record<string, Profile> = {}
export const biographySources: Record<string, { name: string; url: string }> = {}

function profile(id: string, name: string, birth: string, death: string, description: string,
  references: [string, string][], points: [string, string][], note?: string) {
  const sourceIds = references.map(([title, url], index) => {
    const key = `bio-${id}-${index}`
    biographySources[key] = { name: title, url }
    return key
  })
  profiles[id] = { lifespan: `${birth}—${death}`, description,
    milestones: [{ date: birth, text: `${name}出生。` }, ...points.map(([date, text]) => ({ date, text })),
      { date: death, text: `${name}去世。` }], sources: sourceIds, biographyNote: note }
}

