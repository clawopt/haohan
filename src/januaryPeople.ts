export const januaryPeopleSources: Record<string, { name: string; url: string }> = {}
type Reference = [name: string, url: string]
type Chapter = [period: string, text: string]
const wiki = (slug: string): Reference => ['维基百科 · 人物条目（辅助生平资料）', `https://en.wikipedia.org/wiki/${slug}`]
const encyclopedia = (slug: string): Reference => ['大英百科全书 · 人物生平', `https://www.britannica.com/biography/${slug}`]
const aks = (id: string): Reference => ['韩国学中央研究院 · 韩国民族文化大百科', `https://encykorea.aks.ac.kr/Article/${id}`]

function person(id: string, name: string, lifespan: string, subtitle: string, aliases: string[],
  chapters: [Chapter, Chapter, Chapter], references: Reference[], note?: string) {
  const biography: BiographySection[] = chapters.map(([period, text], index) => ({
    title: ['早年与成长', '主要经历与事迹', '晚年与历史影响'][index], period, text,
  }))
  const keys = references.map(([label, url], index) => {
    const key = `jan-life-${id}-${index}`
    januaryPeopleSources[key] = { name: `${name} · ${label}`, url }
    return key
  })
  januaryPeople.push({ id, name, type: '人物', lifespan, subtitle,
    description: biography[1].text, milestones: [], biography,
    biographySources: keys, sources: keys, biographyNote: note ??
      (references.some(([label]) => label.includes('辅助生平资料')) ? '生平含百科辅助资料，尚未逐项与原始档案校验。' : undefined) })
  for (const alias of [name, ...aliases]) januaryPeopleAliases[alias] = id
}

