const section = (title: string, period: string, text: string): BiographySection => ({ title, period, text })
function biography(id: string, sections: BiographySection[], references: [string, string][] = []) {
  personBiographies[id] = sections
  personBiographyReferences[id] = references.map(([name, url], index) => {
    const key = `life-${id}-${index}`
    personBiographySources[key] = { name, url }
    return key
  })
}
