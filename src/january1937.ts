function record(
  id: string, day: number | undefined, category: Category, title: string, location: string,
  summary: string, detail: string, actors: string[], factions: string[], source: keyof typeof januarySources,
  extra: Partial<HistoryEvent> = {},
): HistoryEvent {
  return {
    id: `jan37-${id}`, year: 1937, month: 1, country: 'china', day,
    date: day ? `1937年1月${day}日` : '1937年1月（未定日）',
    precision: day ? 'day' : 'month', archive: true, category, title, location, summary, detail,
    entities: [...new Set(['china', ...actors, ...factions])], factions, source, topicIds: [],
    evidenceNote: day ? '日期指本条所记活动的发生日；史料未提供的小时、对话和个人行程不作补写。' : '所引资料只记到月份，确切日期未定；展示时放在月中附近，不据此认定发生日。',
    ...extra,
  }
}
